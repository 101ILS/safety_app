class AiChatService {
  Future<String> ask(String question) async {
    await Future.delayed(const Duration(milliseconds: 700));

    final q = question.toLowerCase();
    if (q.contains('пожар')) {
      return 'При пожаре: 1) сохраняйте спокойствие; 2) сообщите ответственному лицу; 3) вызовите службу спасения; 4) покиньте зону по эвакуационному маршруту; 5) не используйте лифт.';
    }
    if (q.contains('электро') || q.contains('зазем')) {
      return 'Перед работой с электрооборудованием проверьте заземление, целостность кабелей, маркировку, отсутствие влаги и свободный доступ к отключающим устройствам.';
    }
    return 'Рекомендация: уточните объект проверки, источник риска и рабочую ситуацию. Я помогу составить краткий безопасный порядок действий.';
  }
}
