import 'dart:convert';
import 'openai_service.dart';

class AiQuestionService {
  static Future<List<Map<String, dynamic>>> generateQuestions({
    required String position,
    required String department,
    required String risk,
  }) async {
    final prompt = """
 Сгенерируй 6 вопросов по технике безопасности для сотрудника предприятия инженерно-технического проектирования.

 Структура:
 - первые 3 вопроса: ОБЩАЯ техника безопасности;
 - следующие 3 вопроса: техника безопасности по специализации сотрудника.

 Данные сотрудника:
 Должность: $position
 Отдел: $department
 Уровень риска: $risk

 Требования:
 - каждый вопрос должен иметь 3 варианта ответа;
 - только один вариант правильный;
 - answer — индекс правильного ответа: 0, 1 или 2;
 - вопросы должны быть понятными и практическими;
 - не задавай медицинские вопросы;
 - не используй markdown.

 Верни строго JSON массив:
 [
  {
    "question": "Вопрос",
    "options": ["Вариант 1", "Вариант 2", "Вариант 3"],
    "answer": 1
  }
 ]
   """;

    final response = await OpenAiService.rawRequest(prompt);

    if (response == null) return _fallback();

    try {
      final cleaned = response
          .replaceAll('```json', '')
          .replaceAll('```', '')
          .trim();

      final decoded = jsonDecode(cleaned);

      if (decoded is List) {
        return decoded.map((e) => Map<String, dynamic>.from(e)).toList();
      }
    } catch (_) {}

    return _fallback();
  }

